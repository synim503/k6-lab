#!/bin/sh
# k6-lab: перенос настроек и данных из прежней установки в новую (при переустановке из нового архива).
# Админка хранит в своём каталоге: config/ (подключение к PostgreSQL и КЛЮЧ ШИФРОВАНИЯ секретов) и data/ (файлы версий
# скриптов, архивы запусков). Если их не перенести, записи о скриптах в базе останутся, а файлов не будет.
#
#   ./upgrade.sh /путь/к/старому/k6-lab
set -e
OLD="$1"
[ -n "$OLD" ] || { echo "Использование: $0 /путь/к/старому/k6-lab"; exit 2; }
[ -d "$OLD" ] || { echo "Каталог $OLD не найден"; exit 2; }
cd "$(dirname "$0")"
NEW="$(pwd)"
[ "$(cd "$OLD" && pwd)" != "$NEW" ] || { echo "Старая и новая установки - один каталог, переносить нечего"; exit 0; }
for d in config data; do
  if [ -d "$OLD/$d" ]; then
    mkdir -p "$d"
    cp -a "$OLD/$d/." "$d/"
    echo "Перенесено: $d/"
  else
    echo "В $OLD нет $d/ - пропускаем"
  fi
done
echo "Готово. Остановите старую админку (если запущена) и запустите ./start.sh в этом каталоге."
